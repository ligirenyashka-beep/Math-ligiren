export function findCourseTopic(topicId: string) {
  for (const grade of COURSES) {
    for (const chapter of grade.chapters) {
      const topic = chapter.topics.find((tp) => tp.id === topicId);
      if (topic) return { grade, chapter, topic };
    }
  }
  return null;
}

export function findCourseGrade(gradeId: string) {
  return COURSES.find((g) => g.id === gradeId) ?? null;
}

export const COURSE_TOPIC_COUNT = COURSES.reduce(
  (s, g) => s + g.chapters.reduce((c, ch) => c + ch.topics.length, 0),
  0,
);
